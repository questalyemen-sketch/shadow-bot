# =========================================================
# البحث عن الإجابة
# =========================================================

def find_answer(user_text):

    normalized = normalize_text(user_text)

    if not normalized:
        return None

    # تطابق مباشر
    if normalized in RESPONSES:
        return random.choice(RESPONSES[normalized])

    # البحث عن مفتاح موجود داخل السؤال
    for question, answers in RESPONSES.items():

        normalized_question = normalize_text(question)

        if normalized_question in normalized:
            return random.choice(answers)

    # البحث العكسي
    for question, answers in RESPONSES.items():

        normalized_question = normalize_text(question)

        if normalized in normalized_question:
            return random.choice(answers)

    return None


